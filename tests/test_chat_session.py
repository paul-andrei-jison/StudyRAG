def test_a_follow_up_is_rewritten_and_searched_by_the_standalone_query(setup):
    client = ScriptedClient([GOOD, ["Water covers 71% of the surface [1]."]], rewrites=["How much of Earth's surface is covered by water?"])
    session = setup.session(client)
    session.ask(QUESTION)
    final = session.ask("and how much is water?")
    assert client.chat_calls and final.rewritten and final.query == "How much of Earth's surface is covered by water?"
    assert "71%" in final.sources[0].text                     # retrieval followed the rewritten query
    second_prompt = client.stream_calls[1]
    assert [m["role"] for m in second_prompt] == ["system", "user", "assistant", "user"]
    assert second_prompt[1]["content"] == QUESTION and "SOURCES" not in second_prompt[1]["content"]  # old sources are not resent
    assert second_prompt[-1]["content"].endswith("Question: and how much is water?")  # the model sees what the student typed


