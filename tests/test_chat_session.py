def test_an_uncited_answer_names_the_source_whose_wording_matches(setup):
    # the model cited only a worksheet question number (invalid) but its words come straight from SOURCE 1
    client = ScriptedClient([["The magnetic field of Earth is generated by the movement of molten iron in the outer core [7]."]])
