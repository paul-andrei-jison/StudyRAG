import threading

import pytest

from chat_helpers import ScriptedClient, add_doc, make_setup
from ingest_helpers import make_photo
from studybuddy.chat.answers import ANSWERED, NOT_IN_PAPERS_STATUS
from studybuddy.chat.gate import GateConfig
from studybuddy.errors import ChatContextError, IndexMismatchError, TransientLLMError
from studybuddy.ingest.subjects import SubjectList
from studybuddy.ui.chat import (DONE, FAILED, SEARCHING, STREAMING, WAKING, friendly_error, render_answer, source_choices,
                                source_details, sources_caption, stream_turn)
from studybuddy.ui.files import LibraryGuard

QUESTION = "What generates the magnetic field of Earth?"
GOOD = ["The field is generated by molten iron ", "in the outer core ", "[", "1", "]", "."]


@pytest.fixture
def setup(settings, tmp_path):
    s = make_setup(settings, tmp_path)
    yield s
    s.index.close()


def run(setup, client, question=QUESTION, subject=None, session=None, **kw):
    session = session or setup.session(client)
    return session, list(stream_turn(session, question, subject, **kw))


def test_updates_stream_in_order_and_end_with_the_checked_answer(setup):
    _, updates = run(setup, ScriptedClient([GOOD]))
    phases = [u.phase for u in updates]
    assert phases[-1] == DONE and set(phases[:-1]) == {STREAMING}
    texts = [u.text for u in updates[:-1]]
    assert all(b.startswith(a) for a, b in zip(texts, texts[1:]))  # each update extends the last: nothing is rewritten
    final = updates[-1]
    assert final.answer.status == ANSWERED and final.answer.cited == [1]
    assert final.text.startswith("The field is generated by molten iron in the outer core [1].")


def test_the_subject_filter_reaches_the_session_and_unknown_ones_are_reported(setup):
    names = SubjectList(setup.settings.data_dir / "subjects.json", ["Science", "Geography"])
    session = setup.session(ScriptedClient([GOOD]), subjects=names)
    _, updates = run(setup, None, subject="geography", session=session)
    assert session.subject == "Geography" and updates[-1].answer.subject_filter == "Geography"
    _, bad = run(setup, ScriptedClient(), subject="Cooking", session=setup.session(ScriptedClient(), subjects=names))
    assert [u.phase for u in bad] == [FAILED] and "Unknown subject" in bad[0].text


def test_the_waking_state_shows_while_nothing_has_arrived_and_goes_away(setup):
    release = threading.Event()

    class Slow(ScriptedClient):
        def chat_stream(self, messages, temperature=0.0, max_tokens=None):
            assert release.wait(20)
            yield from super().chat_stream(messages, temperature, max_tokens)

    session = setup.session(Slow([GOOD]))
    seen = []
    for update in stream_turn(session, QUESTION, None, wake_after=0.15, search_after=0.03, poll=0.02):
        seen.append(update)
        if update.phase == WAKING and not release.is_set():
            release.set()
    assert seen[0].phase == SEARCHING and "Searching your papers" in seen[0].text   # a warm model is not accused of sleeping
    waking = [u for u in seen if u.phase == WAKING]
    assert waking and "Waking the model, this can take a minute" in waking[0].text
    assert seen[-1].phase == DONE and "Waking" not in seen[-1].text
    assert all(u.phase != WAKING for u in seen[seen.index(waking[-1]) + 1:])  # no waking text once the answer flows


def test_a_fast_answer_never_shows_the_waking_state(setup):
    _, updates = run(setup, ScriptedClient([GOOD]), wake_after=30.0, search_after=30.0)
    assert {u.phase for u in updates} <= {STREAMING, DONE}


def test_a_refusal_is_shown_as_not_in_your_papers_with_the_closest_pages(setup):
    session = setup.session(ScriptedClient(), gate=GateConfig(0.99, 0.99, 1.0))
    _, updates = run(setup, None, question="Who won the football world cup in 1998?", session=session)
    answer = updates[-1].answer
    assert answer.status == NOT_IN_PAPERS_STATUS
    text = updates[-1].text
    assert text.startswith("**Not in your papers.**") and "probably not relevant" in text and "Why:" in text
    assert sources_caption(answer).startswith("Closest pages (probably not relevant)")
    assert all(not s.cited for s in answer.sources)


def test_quality_notes_are_a_separate_callout_and_the_cited_page_is_marked(setup):
    add_doc(setup.index, "blurry", "Tectonic plates slowly move over the mantle on the blurry page.", subject="Geography",
            title="Blurry plates", quality=0.4, flags=["low_agreement"])
    client = ScriptedClient([["Plates move over the mantle ", "[1]", "."]])
    _, updates = run(setup, client, question="How do tectonic plates move over the mantle?")
    answer = updates[-1].answer
    text = updates[-1].text
    assert "> **Check this:** page 1 of 'Blurry plates' was hard to read" in text
    assert text.index("Plates move over the mantle") < text.index("Check this")
    labels = [label for label, _ in source_choices(answer)]
    assert labels[0].startswith("[1]") and "cited" in labels[0] and "hard to read" in labels[0]


def test_cited_sources_are_listed_first(setup):
    client = ScriptedClient([["The field comes from molten iron [2]."]])
    _, updates = run(setup, client)
    answer = updates[-1].answer
    numbers = [n for _, n in source_choices(answer)]
    assert numbers[0] == 2 and sorted(numbers) == [s.number for s in answer.sources]


def test_an_uncited_answer_keeps_its_caution(setup):
    _, updates = run(setup, ScriptedClient([["It is something deep inside the planet."]]))
    assert "> **Check this:** " in updates[-1].text and "no source was cited" in updates[-1].text


def test_new_chat_forgets_the_conversation_but_keeps_the_filter(setup):
    session = setup.session(ScriptedClient([GOOD, GOOD]))
    run(setup, None, session=session, subject=None)
    assert len(session.history) == 1
    session.new()
    assert session.history == [] and session.last_answer is None


@pytest.mark.parametrize("error, expected", [
    (TransientLLMError("connection refused"), "can't reach the language model"),
    (ChatContextError("the loaded context is 1100 tokens"), "the loaded context is 1100 tokens"),
    (IndexMismatchError("embedding model changed"), "index_admin.py reindex"),
    (ValueError("The question is empty."), "The question is empty."),
    (RuntimeError("boom"), "Something went wrong (RuntimeError: boom)"),
])
def test_errors_become_plain_messages_without_tracebacks(setup, error, expected):
    _, updates = run(setup, ScriptedClient([error]))
    assert updates[-1].phase == FAILED and expected in updates[-1].text and "Traceback" not in updates[-1].text
    assert friendly_error(error) == updates[-1].text


def test_an_error_after_some_text_keeps_the_partial_answer_with_a_warning(setup):
    pieces = ["Molten iron moves ", TransientLLMError("connection dropped")]
    _, updates = run(setup, ScriptedClient([pieces]))
    answer = updates[-1].answer
    assert answer.truncated and "Incomplete" in updates[-1].text and "connection dropped" in updates[-1].text


def test_source_details_open_the_page_image_with_file_and_page(setup, tmp_path):
    photo = make_photo(tmp_path / "lib" / "Science" / "earth.jpg")
    add_doc(setup.index, "real", "Volcanoes erupt molten rock from the mantle onto the surface.", subject="Science",
            title="Volcanoes", path=str(photo))
    _, updates = run(setup, ScriptedClient([["Volcanoes erupt molten rock [1]."]]), question="What do volcanoes erupt?")
    answer = updates[-1].answer
    number = next(s.number for s in answer.sources if s.title == "Volcanoes")
    answer.cited = [number]
    answer.sources[number - 1].cited = True
    guard = LibraryGuard(tmp_path / "lib")
    image, info, page_text = source_details(answer, number, guard)
    assert image is not None and image.size == (300, 400)
    assert f"File: {photo}" in info and "Page: 1" in info and "was cited" in info
    assert "molten rock" in page_text


def test_source_details_explain_a_missing_or_foreign_image_instead_of_failing(setup, tmp_path):
    _, updates = run(setup, ScriptedClient([GOOD]))
    answer = updates[-1].answer
    image, info, _ = source_details(answer, 1, LibraryGuard(tmp_path / "lib"))  # the fixture path C:/lib/... is not in this library
    assert image is None and "Page image not shown" in info and "File: " in info
    assert source_details(answer, 99, LibraryGuard(tmp_path / "lib"))[0] is None


def test_markdown_in_a_page_cannot_change_the_label_list(setup):
    add_doc(setup.index, "html", "Magnetic field of Earth <script>alert(1)</script> molten iron core.", title="<b>x</b>")
    _, updates = run(setup, ScriptedClient([["Molten iron [1]."]]))
    # labels are plain strings for a Radio; the page text goes to a plain textbox, never to markdown
    assert all(isinstance(label, str) for label, _ in source_choices(updates[-1].answer))
    assert render_answer(updates[-1].answer).count("<script>") == 0
