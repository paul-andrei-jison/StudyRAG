def test_temperature_zero_and_the_answer_reserve_are_sent(setup):
    seen = {}
    client = ScriptedClient([GOOD])
    original = client.chat_stream

    def spy(messages, temperature=0.0, max_tokens=None):
        seen.update(temperature=temperature, max_tokens=max_tokens)
        return original(messages, temperature, max_tokens)

    client.chat_stream = spy
    ask(setup, client)
    assert seen == {"temperature": 0.0, "max_tokens": 700}


