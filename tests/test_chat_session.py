def test_a_cited_low_quality_page_is_called_out_by_the_program_not_the_model(setup):
    add_doc(setup.index, "blurry", "The mantle lets tectonic plates move because it flows slowly.", title="Blurry plates",
            quality=0.3, flags=["possible_omission", "glare"])
    client = ScriptedClient([["Plates move on the mantle ", "[1]", "."]])
    _, final = ask(setup, client, question="mantle plates move flows slowly")
    assert final.sources[0].title == "Blurry plates" and final.sources[0].hard_to_read
    assert final.notes[0].startswith("Note: page 1 of 'Blurry plates' was hard to read, check the photo")
    assert "some text may have been missed" in final.notes[0] and final.text.endswith(final.notes[0])


def test_a_hard_to_read_page_that_was_not_cited_is_not_mentioned(setup):
    add_doc(setup.index, "blurry", "The mantle lets tectonic plates move because it flows slowly.", title="Blurry plates",
            quality=0.3, flags=["possible_omission"])
    client = ScriptedClient([["The core makes the field ", "[2]", "."]])  # cites a different source
    _, final = ask(setup, client, question="mantle plates move flows slowly magnetic")
    cited_titles = {s.title for s in final.cited_sources}
    assert "Blurry plates" not in cited_titles and not any("hard to read" in n for n in final.notes)


