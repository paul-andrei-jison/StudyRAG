@pytest.fixture
def setup(settings, tmp_path):
    s = make_setup(settings, tmp_path)
    yield s
    s.index.close()


def ask(setup, client, question=QUESTION, **kw):
    session = setup.session(client, **kw)
    return session, session.ask(question)


# ---- a normal answer -------------------------------------------------------------------------

def test_streams_the_answer_then_returns_the_checked_final_answer(setup):
    client = ScriptedClient([GOOD], usage={"prompt_tokens": 500, "completion_tokens": 20})
    session = setup.session(client, clock=Clock())
    items = list(session.ask_stream(QUESTION))
    pieces, final = items[:-1], items[-1]
    assert all(isinstance(p, str) for p in pieces) and isinstance(final, ChatAnswer)
    assert "".join(pieces).strip() == final.text == "The field is generated by molten iron in the outer core [1]."
    assert (final.status, final.cited, final.invalid_citations, final.uncited) == (ANSWERED, [1], [], False)
    assert final.sources[0].cited and final.prompt_tokens == 500 and final.completion_tokens == 20
    assert final.first_token_seconds is not None and final.total_seconds >= final.first_token_seconds > 0
    assert final.context_tokens == 13_721 and final.query == QUESTION and not final.rewritten


def test_sources_carry_subject_file_page_image_and_raw_scores(setup):
    _, final = ask(setup, ScriptedClient([GOOD]))
    top = final.sources[0]
