from studybuddy.llm import StreamEnd
from studybuddy.reader.quality import PageRecord

EARTH = ("The magnetic field of Earth is generated by the movement of molten iron in the outer core. "
         "This field protects the atmosphere from harmful particles in the solar wind.")
WATER = ("About 71% of Earth's surface is covered by water. Liquid water is essential for all known forms of life "
         "and it regulates temperature.")
PLATES = "Tectonic plates slowly move over the mantle. Plate tectonics shapes mountains, volcanoes and ocean basins."
LAX_GATE = GateConfig(high_cosine=0.30, low_cosine=0.20, min_coverage=0.3)   # tests do not depend on the calibrated numbers


class ScriptedClient:
    """chat_stream() plays scripted answers (each a list of text pieces, or an Exception to raise); chat() plays rewrites."""

    def __init__(self, answers=(), rewrites=(), context=13_721, usage=None, finish="stop"):
        self.answers, self.rewrites = list(answers), list(rewrites)
        self.context, self.usage, self.finish = context, usage, finish
        self.stream_calls: list[list[dict]] = []
        self.chat_calls: list[list[dict]] = []

    def chat(self, messages, temperature=0.0, max_tokens=None):
        self.chat_calls.append(messages)
        if not self.rewrites:  # nothing scripted: a faithful rewrite that returns the follow-up unchanged
            return messages[-1]["content"].split("Follow-up question: ", 1)[1].splitlines()[0]
        item = self.rewrites.pop(0)
        if isinstance(item, Exception):
            raise item
        return item

    def chat_stream(self, messages, temperature=0.0, max_tokens=None):
        self.stream_calls.append(messages)
        script = self.answers.pop(0)
        if isinstance(script, Exception):
            raise script
        pieces = [script] if isinstance(script, str) else list(script)
        for piece in pieces:
            if isinstance(piece, Exception):
                raise piece
            yield piece
        yield StreamEnd(self.usage, self.finish)

    def context_length(self, model=None):
        return self.context


@dataclass
class Clock:
    now: float = 100.0
    step: float = 0.5

    def __call__(self):
        self.now += self.step
        return self.now


@dataclass
class Setup:
    index: Index
    embedder: FakeEmbedder
    settings: object
    docs: dict = field(default_factory=dict)

    def session(self, client, **kw):
        kw.setdefault("gate", LAX_GATE)
        return ChatSession(self.index, client, self.settings, **kw)


def add_doc(index, key, text, subject="Science", title=None, pages=None, quality=0.95, flags=(), path=None):
    """Index one document. `pages` is a list of texts (one page each); default is a single page of `text`."""
    texts = pages or [text]
    path = path or f"C:/lib/{subject}/{key}.jpg"
    records = [PageRecord(i, path, "image", text=t, quality=quality, flags=list(flags)) for i, t in enumerate(texts, 1)]
    return index.add_document(DocumentMeta(key, path, "photo", subject, title or key.title()), records)


def make_setup(settings, tmp_path) -> Setup:
    import dataclasses
    s = dataclasses.replace(settings, data_dir=tmp_path / "data", library_dir=tmp_path / "lib")
    emb = FakeEmbedder()
    index = Index.open(s, emb)
    add_doc(index, "earth", EARTH, title="Earth notes")
    add_doc(index, "water", WATER, title="Water facts")
    add_doc(index, "plates", PLATES, subject="Geography", title="Plate tectonics")
    return Setup(index, emb, s)
