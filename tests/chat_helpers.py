"""Shared pieces for the chat tests: a scripted streaming client and a small real index."""
from __future__ import annotations

from dataclasses import dataclass, field

from conftest import FakeEmbedder
from studybuddy.chat.session import ChatConfig, ChatSession
from studybuddy.chat.gate import GateConfig
from studybuddy.index.index import Index
