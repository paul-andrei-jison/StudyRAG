CFG = GateConfig(high_cosine=0.70, low_cosine=0.60, min_coverage=0.5)
ROOT = Path(__file__).resolve().parents[1]


def hit(text="Earth has a magnetic field", cosine=0.75, doc=1, page=1, chunk=1):
    return Hit(chunk_id=chunk, doc_id=doc, score=0.03, text=text, snippet="", subject="S", title="T", file_path="f.jpg",
               page_number=page, image_path="f.jpg", page_quality=1.0, page_flags=[], vector_score=cosine)


# ---- coverage ------------------------------------------------------------------------------

def test_word_forms_link_plurals_and_endings():
    assert "plate" in forms("plates") and "gas" in forms("gases") and "move" in forms("moving") and "cover" in forms("covered")
    assert forms("is") == {"is"} and forms("sing") == {"sing"}  # short words are not chopped up
    assert forms("plates") & forms("plate") and forms("moving") & forms("move") and forms("gases") & forms("gas")


def test_coverage_counts_content_words_ignoring_endings():
    text = "The magnetic field is generated by moving molten iron in the outer core."
    assert coverage("What generates Earth's magnetic field?", text) == pytest.approx(0.75)  # generates~generated, magnetic, field; not earth
    assert coverage("How does molten iron move?", text) == 1.0                              # move~moving
    assert coverage("", text) == 0.0


def test_coverage_ignores_stopwords_and_case():
    assert coverage("WHAT IS THE MAGNETIC FIELD", "magnetic field") == 1.0
    assert coverage("magnetic field", "") == 0.0
    assert coverage("???", "anything") == 0.0


# ---- signals -------------------------------------------------------------------------------

def test_signals_use_the_best_cosine_chunk_for_coverage():
    hits = [hit("unrelated words here", 0.55, chunk=1), hit("magnetic field of Earth", 0.78, chunk=2)]
    s = signals_for(hits, "magnetic field")
    assert s.top_cosine == 0.78 and s.coverage == 1.0 and s.max_coverage == 1.0 and s.sources == 2


def test_signals_with_no_hits():
    s = signals_for([], "anything")
    assert s == Signals(None, 0.0, 0.0, 0)


def test_signals_without_vector_scores_fall_back_to_keywords():
    h = hit("magnetic field", None)
    s = signals_for([h], "magnetic field")
    assert s.top_cosine is None and s.coverage == 1.0


# ---- the rule ------------------------------------------------------------------------------

@pytest.mark.parametrize("cosine,cover,expected", [
    (0.80, 0.0, True),     # strong semantic match: answerable even with no shared words
    (0.70, 0.0, True),     # exactly at HIGH
    (0.699, 0.0, False),   # just under HIGH, no keywords
    (0.65, 0.5, True),     # moderate and the words agree (exactly at COVERAGE)
    (0.65, 0.49, False),   # moderate but the words do not
    (0.60, 0.5, True),     # exactly at LOW
    (0.599, 1.0, False),   # under LOW: even full keyword coverage is not enough
    (0.52, 0.2, False),    # the unrelated range
])
def test_the_two_threshold_rule(cosine, cover, expected):
    ok, reason = decide(Signals(cosine, cover, cover, 3), CFG)
    assert ok is expected and reason


def test_nothing_found_is_a_refusal():
    ok, reason = decide(Signals(None, 0.0, 0.0, 0), CFG)
    assert not ok and "nothing was found" in reason


def test_keyword_only_evidence_needs_strong_coverage():
    assert decide(Signals(None, 1.0, 1.0, 2), CFG)[0] is True
    assert decide(Signals(None, 0.6, 0.6, 2), CFG)[0] is False  # no semantic check: demand more than COVERAGE


def test_reasons_explain_the_decision_in_plain_words():
    assert "strong match" in decide(Signals(0.8, 0, 0, 1), CFG)[1]
    assert "moderate match" in decide(Signals(0.65, 0.6, 0.6, 1), CFG)[1]
    weak = decide(Signals(0.52, 0.2, 0.3, 1), CFG)[1]
    assert "weak match" in weak and "0.52" in weak and "20%" in weak


def test_assess_combines_signals_and_decision():
    a = assess([hit("magnetic field of Earth", 0.74)], "what is the magnetic field", CFG)
    assert a.answerable and a.signals.top_cosine == 0.74
    assert not assess([hit("rivers", 0.5)], "magnetic field", CFG).answerable
    assert not assess([], "magnetic field", CFG).answerable


def test_defaults_are_a_valid_configuration():
    d = GateConfig()
    assert 0 < d.low_cosine <= d.high_cosine < 1 and 0 < d.min_coverage <= 1


# ---- calibration maths ---------------------------------------------------------------------

def scored(kind, cosine, cover=0.0, q="q"):
    return Scored(Case(q, kind), Signals(cosine, cover, cover, 3))


TABLE = [
    scored(ANSWERABLE, 0.80), scored(ANSWERABLE, 0.76), scored(ANSWERABLE, 0.72), scored(ANSWERABLE, 0.66, 0.67),
    scored(ANSWERABLE, 0.63, 0.5),
    scored(FAR, 0.52), scored(FAR, 0.50), scored(FAR, 0.55),
    scored(NEAR, 0.64, 0.2), scored(NEAR, 0.58, 0.3), scored(NEAR, 0.61, 0.0),
]


def test_evaluate_counts_both_kinds_of_mistake():
    r = evaluate(TABLE, CFG)
    assert (r.n_answerable, r.n_unanswerable) == (5, 6)
    assert r.false_refusals == 0 and r.false_answers == 0 and r.far_false_answers == 0
    lax = evaluate(TABLE, GateConfig(0.5, 0.5, 0.0))
    assert lax.false_answers == 6 and lax.far_false_answers == 3 and lax.near_false_answers == 3 and lax.false_refusals == 0
    strict = evaluate(TABLE, GateConfig(0.99, 0.99, 1.0))
    assert strict.false_refusals == 5 and strict.false_answers == 0


def test_rates_are_fractions_and_safe_on_empty_sets():
    r = evaluate(TABLE, GateConfig(0.99, 0.99, 1.0))
    assert r.false_refusal_rate == 1.0 and r.false_answer_rate == 0.0
    empty = evaluate([], CFG)
    assert empty.false_refusal_rate == 0.0 and empty.false_answer_rate == 0.0


def test_cost_puts_far_answers_first_then_near_then_refusals():
    from studybuddy.chat.calibrate import Rates
    assert cost(Rates(5, 6, 5, 1, 1, 0)) > cost(Rates(5, 6, 0, 2, 0, 2)) > cost(Rates(5, 6, 3, 0, 0, 0))


def test_choose_finds_a_perfect_configuration_when_one_exists():
    config, rates = choose(TABLE)
    assert rates.false_answers == 0 and rates.false_refusals == 0
    assert evaluate(TABLE, config) == rates
    assert config.low_cosine <= config.high_cosine


def test_choose_when_the_classes_overlap_prefers_no_far_answers_over_no_refusals():
    overlapping = [scored(ANSWERABLE, 0.75), scored(ANSWERABLE, 0.55), scored(FAR, 0.56), scored(FAR, 0.50), scored(NEAR, 0.70, 0.9)]
    config, rates = choose(overlapping)
    assert rates.far_false_answers == 0
    assert rates.false_refusals >= 1 or rates.near_false_answers >= 1  # the overlap cannot be fully resolved


def test_sweep_covers_many_configurations_and_respects_ordering():
    results = sweep(TABLE)
    assert len(results) > 50 and all(c.low_cosine <= c.high_cosine for c, _ in results)


def test_table_and_rates_text():
    text = format_table(TABLE, CFG)
    assert text.startswith("kind") and "answerable" in text and "far" in text and "near" in text
    wrong = format_table([scored(FAR, 0.9)], CFG)
    assert "WRONG" in wrong and "ANSWER" in wrong
    rates = format_rates(evaluate(TABLE, CFG), CFG)
    assert "false refusals: 0/5 = 0%" in rates and "false answers: 0/6 = 0%" in rates


# ---- collecting signals from a real index and loading cases --------------------------------

def test_collect_runs_retrieval_like_chat_does(settings):
    idx = Index.open(settings, FakeEmbedder())
    text = "The magnetic field of Earth is generated by molten iron in the outer core."
    idx.add_document(DocumentMeta("h1", "f.jpg", "photo", "Science", "Earth"), [PageRecord(1, "f.jpg", "image", text=text, quality=1.0)])
    cases = [Case("what generates the magnetic field of Earth", ANSWERABLE), Case("who won the football world cup", FAR)]
    got = collect(lambda q: idx.search(q, k=20), cases)
    assert got[0].signals.top_cosine > got[1].signals.top_cosine
    assert got[0].signals.coverage > got[1].signals.coverage
    idx.close()


def test_load_cases(tmp_path):
    (tmp_path / "questions.json").write_text(json.dumps([{"question": "a?", "expect": ["x"]}, {"question": "b?", "expect": ["y"]}]))
    (tmp_path / "unanswerable.json").write_text(json.dumps([{"question": "c?", "kind": "far"}, {"question": "d?", "kind": "near"}, {"question": "e?"}]))
    cases = load_cases(tmp_path)
    assert [(c.question, c.kind) for c in cases] == [("a?", ANSWERABLE), ("b?", ANSWERABLE), ("c?", FAR), ("d?", NEAR), ("e?", FAR)]
    (tmp_path / "unanswerable.json").write_text(json.dumps([{"question": "x", "kind": "weird"}]))
    with pytest.raises(ValueError, match="kind"):
        load_cases(tmp_path)
    (tmp_path / "unanswerable.json").unlink()
    assert len(load_cases(tmp_path)) == 2  # the unanswerable file is optional


def test_calibration_script_without_samples_exits_cleanly(tmp_path):
    env = {**os.environ, "SB_READER_MODEL": "r", "SB_CHAT_MODEL": "c", "SB_EMBED_MODEL": "e",
           "SB_LIBRARY_DIR": str(tmp_path / "lib"), "SB_DATA_DIR": str(tmp_path / "data"), "SB_SAMPLES_DIR": str(tmp_path / "none")}
    out = subprocess.run([sys.executable, str(ROOT / "scripts" / "calibrate_gate.py")], capture_output=True, text=True,
                         env=env, cwd=tmp_path, timeout=60)
    assert out.returncode == 0 and "questions.json" in out.stdout


# ---- the calibrated defaults, on the score ranges observed on real pages (numbers only) ------------

OBSERVED = [  # (kind, top cosine, coverage) from the 2026-10-17 calibration run: 13 answerable, 6 far-off, 6 near-miss
    *[(ANSWERABLE, c, v) for c, v in [(0.818, 1.0), (0.807, 0.8), (0.803, 0.5), (0.796, 1.0), (0.788, 0.8), (0.783, 0.75), (0.759, 0.5),
                                      (0.751, 0.86), (0.739, 0.6), (0.702, 0.8), (0.701, 0.33), (0.681, 0.75), (0.665, 1.0)]],
    *[(FAR, c, v) for c, v in [(0.622, 0.0), (0.593, 0.0), (0.535, 0.14), (0.534, 0.0), (0.498, 0.0), (0.488, 0.0)]],
    *[(NEAR, c, v) for c, v in [(0.725, 0.75), (0.715, 0.5), (0.695, 0.33), (0.668, 0.25), (0.626, 0.0), (0.598, 0.5)]],
]


def test_calibrated_defaults_on_the_observed_scores():
    table = [scored(kind, cosine, cover) for kind, cosine, cover in OBSERVED]
    r = evaluate(table, GateConfig())
    assert r.false_refusals == 0 and r.far_false_answers == 0   # nothing answerable refused, nothing far-off let through
    assert r.near_false_answers == 3                            # near-misses reach the model, which refuses them itself
    assert (r.n_answerable, r.n_unanswerable) == (13, 12)


def test_calibrated_defaults_keep_a_margin_to_the_observed_scores():
    d = GateConfig()
    far_max = max(c for k, c, _ in OBSERVED if k == FAR)
    answerable_by_high = [c for k, c, _ in OBSERVED if k == ANSWERABLE and c >= d.high_cosine]
    assert d.low_cosine - far_max >= 0.015            # the far-off questions stay clear of LOW
    assert min(answerable_by_high) - d.high_cosine >= 0.0 and 0.60 < d.low_cosine < d.high_cosine < 0.75
